import mongoose from 'mongoose';
import dotenv from 'dotenv';
import fs from 'fs';
dotenv.config();
await mongoose.connect(process.env.MONGODB_URI);
const Category = mongoose.model('Category', new mongoose.Schema({}, { strict:false }));
const Template = mongoose.model('Template', new mongoose.Schema({}, { strict:false }));
const cats = await Category.find().lean();
const tmpls = await Template.find().lean();
const stamp = '20260625';
fs.writeFileSync(`_backup_categories_${stamp}.json`, JSON.stringify(cats,null,2));
fs.writeFileSync(`_backup_templates_${stamp}.json`, JSON.stringify(tmpls,null,2));
console.log(`Backed up ${cats.length} categories, ${tmpls.length} templates to _backup_*_${stamp}.json`);
await mongoose.disconnect();
