import mongoose from 'mongoose';

const ProductionCardSchema = new mongoose.Schema({
  orderId: { type: mongoose.Schema.Types.Mixed, required: true },
  templateId: { type: mongoose.Schema.Types.Mixed, required: true },
  customerName: { type: String },
  projectName: { type: String },
  templateName: { type: String },
  measurements: { type: mongoose.Schema.Types.Mixed },

  productionDate: { type: Date },
  status: { 
    type: String, 
    enum: ['Created', 'Processing', 'Verification Pending', 'Proceed for Production', 'Start', 'In Production', 'Completed', 'Dispatched', 'Cancelled'], 
    default: 'Created' 
  },
  qty: { type: Number, default: 1 },
  priority: { 
    type: String, 
    enum: ['Low', 'Normal', 'High', 'Urgent'], 
    default: 'Normal' 
  },
  notes: { type: String, default: '' },
  runningCount: { type: Number, default: 0 },
  dispatchDismissed: { type: Boolean, default: false },
  
  // Factory Outputs (Generated by Engine)
  cuttingList: [{
    materialName: String,
    cutLength: mongoose.Schema.Types.Mixed,
    qty: Number
  }],
  glassList: [{
    glassType: String,
    width: Number,
    height: Number,
    qty: Number
  }],
  hardwareList: [{
    hardwareName: String,
    qty: Number
  }],
  totalBomConsumption: [{
    materialName: String,
    category: String,
    qty: Number,
    unit: String
  }]
}, { timestamps: true });

export default mongoose.model('ProductionCard', ProductionCardSchema);

