import { MongoClient } from 'mongodb';
const c = new MongoClient('mongodb://127.0.0.1:27017');
await c.connect();
const db = c.db('aran_erp');
const col = db.collection('templates');
const imported = await col.find({ templateType: { $ne: 'REACT_COMPONENT' } }).project({ code:1, name:1, templateType:1, status:1 }).toArray();
const reactCount = await col.countDocuments({ templateType: 'REACT_COMPONENT' });
console.log('REACT_COMPONENT total:', reactCount);
console.log('Remaining (non-react):', imported.length);
for (const t of imported) console.log(' ', t.code, '|', t.templateType, '|', t.status, '|', t.name);
await c.close();
